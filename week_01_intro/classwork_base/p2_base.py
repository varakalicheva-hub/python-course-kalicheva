#
#   In: hi
#   Out: (ничего)
#
# Подсказка:
#   if (n := len(s)) > 5:
#       print(n)

def task_2_4(s: str) -> int | None:
    if (n := len(s)) > 5: # почему n а не s? потому что n это длина строки, а s сама строка. а откуда он знает, что n это длина строки? потому что мы присвоили n значение len(s) в скобках.
        print(n)
    else:
        print(None)


